CREATE TABLE avatar_settings (
    avatar_id bigint NOT NULL REFERENCES avatars(id),
    setting_key text NOT NULL,
    setting_value text NOT NULL,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (avatar_id, setting_key)
);

CREATE TABLE avatar_cards (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avatar_id bigint NOT NULL REFERENCES avatars(id),
    product_id integer NOT NULL,
    clip text NOT NULL,
    sub_type text NOT NULL,
    roles text NOT NULL DEFAULT 'AA==',
    source text NOT NULL DEFAULT 'SYSTEM',
    active integer NOT NULL DEFAULT 0,
    quantity integer NOT NULL DEFAULT 1,
    color integer NOT NULL DEFAULT 0,
    expire bigint NOT NULL DEFAULT 0,
    life_time bigint NOT NULL DEFAULT 0,
    transferrable boolean NOT NULL DEFAULT false,
    base integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_avatar_cards_avatar_id ON avatar_cards (avatar_id);
CREATE UNIQUE INDEX ux_avatar_cards_avatar_clip ON avatar_cards (avatar_id, clip);

CREATE TABLE avatar_achievements (
    avatar_id bigint NOT NULL REFERENCES avatars(id),
    achievement_id integer NOT NULL,
    meta_key text NOT NULL,
    current_step integer NOT NULL DEFAULT 1,
    total_step integer NOT NULL DEFAULT 3,
    current_value integer NOT NULL DEFAULT 0,
    status text NOT NULL DEFAULT 'ONGOING',
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (avatar_id, achievement_id)
);

CREATE TABLE avatar_permissions (
    avatar_id bigint NOT NULL REFERENCES avatars(id),
    permission_key text NOT NULL,
    role_index integer NOT NULL,
    granted_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (avatar_id, permission_key)
);