CREATE TABLE accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    password_hash text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX ux_accounts_email_lower ON accounts (lower(email));

CREATE TABLE avatars (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id),
    avatar_id text NOT NULL UNIQUE,
    avatar_name text NOT NULL,
    gender text NOT NULL,
    privilege_id integer NOT NULL DEFAULT 1,
    sanil integer NOT NULL DEFAULT 30000,
    diamond integer NOT NULL DEFAULT 100,
    universe_key text NOT NULL DEFAULT 'w1',
    room_key text NOT NULL DEFAULT 'airport',
    position text NOT NULL DEFAULT '15,15',
    direction integer NOT NULL DEFAULT 5,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_avatars_gender CHECK (gender IN ('m', 'f'))
);

CREATE TABLE auth_tokens (
    token_hash text PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts(id),
    avatar_id bigint NOT NULL REFERENCES avatars(id),
    expires_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_auth_tokens_avatar_id ON auth_tokens (avatar_id);
CREATE INDEX ix_auth_tokens_expires_at ON auth_tokens (expires_at);